  /// Logika 3 Kartu Simetris Paket Populer (PRD Bagian 14.3 — `selectThreePackages`)
  /// Kartu di posisi tengah (indeks 1) otomatis mendapatkan sorotan "⭐ Rekomendasi Teknisi"
  static List<CctvPackage> selectThreePopularPackages(List<CctvPackage> allPackages) {
    final active = allPackages.where((p) => p.isActive).toList();
    if (active.isEmpty) return [];

    final popularOnes = active.where((p) => p.popular).toList();
    final nonPopularOnes = active.where((p) => !p.popular).toList();

    if (active.length < 3) {
      return [...popularOnes, ...nonPopularOnes].take(active.length).toList();
    }

    if (popularOnes.length == 1) {
      return [nonPopularOnes[0], popularOnes[0], nonPopularOnes[1]];
    }

    if (popularOnes.length == 2) {
      return [popularOnes[0], popularOnes[1], nonPopularOnes[0]];
    }

    // Jika >= 3 paket populer, tempatkan Hikvision ColorVu (atau paket populer pertama) di tengah
    final source = popularOnes.length >= 3 ? popularOnes : active;
    final hikColorVuIdx = source.indexWhere((p) => p.id.contains('colorvu'));
    if (hikColorVuIdx == 0 && source.length >= 3) {
      return [source[1], source[0], source[2]];
    }
    return source.take(3).toList();
  }

